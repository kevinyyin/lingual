"""Extended vocabulary: every ASL Citizen sign (2,731, ASL-LEX lexicon) plus WLASL words, with English meanings.

Sources (downloaded, not redistributed): ASL Citizen splits/train.csv (gloss -> ASL-LEX code; training.remote_zip),
ASL-LEX 2.0 sign_props.json (code -> dominant English translation, semantic category; CC BY-NC 4.0), WLASL index
(training.clips_from_wlasl). Writes vocab/vocab_extended.yaml (gitignored); load_vocab merges it after the curated
vocab/vocab.yaml, which keeps priority for any sign both name.

Run: uv run python -m training.build_vocab
"""

import csv
import json
import re
from collections import defaultdict
from pathlib import Path

import yaml

from server.vocab import EXTENDED, load_vocab

ROOT = Path(__file__).resolve().parent.parent
CITIZEN_TRAIN = ROOT / "data" / "asl_citizen" / "splits" / "train.csv"
ASLLEX = ROOT / "data" / "asllex" / "sign_props.json"
ASLLEX_URL = "https://asl-lex.org/visualization/data/sign_props.json"
WLASL_INDEX = ROOT / "data" / "wlasl" / "WLASL_v0.3.json"


def key(s: str) -> str:
    """Spelling-insensitive identity: THANK-YOU, THANKYOU and 'thank you' are one sign."""
    return re.sub(r"[^A-Z0-9]", "", s.upper())


def gloss_name(word: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "-", word.upper()).strip("-")


def meaning(e: dict) -> str:
    """The sign's own English identity: ASL-LEX's lemma ("look_at" -> "look at", "banana_1" -> "banana").
    DominantTranslation is only what raters guessed most often (PICKLE's is "pineapple"), so it is the last resort."""
    lemma = (e.get("LemmaID") or e.get("EntryID") or "").strip().lower()
    lemma = re.sub(r"_\d+$", "", lemma).replace("_", " ").strip()
    return lemma or (e.get("DominantTranslation") or "").strip().lower()


def main() -> None:
    if not ASLLEX.exists():
        import urllib.request

        ASLLEX.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(ASLLEX_URL, ASLLEX)
    lex = {e["Code"]: e for e in json.loads(ASLLEX.read_text(encoding="utf-8"))}
    base = load_vocab(extended=None)
    taken = {key(s.gloss) for s in base.all} | {key(s.asl_citizen) for s in base.all if s.asl_citizen}
    taken_base = {key(re.sub(r"\d+$", "", s.asl_citizen)) for s in base.all if s.asl_citizen}

    # ASL Citizen: variants (WANT1, WANT2) collapse into one sign unless ASL-LEX gives them different meanings
    variants: dict[str, list[tuple[str, dict]]] = defaultdict(list)
    with open(CITIZEN_TRAIN, newline="", encoding="utf-8") as fh:
        for row in list(csv.reader(fh))[1:]:
            name, code = row[2].strip(), row[3].strip()
            base_name = re.sub(r"\d+$", "", name) or name
            if all(n != name for n, _ in variants[base_name]):
                variants[base_name].append((name, lex.get(code, {})))
    signs = []
    for base_name, items in sorted(variants.items()):
        meanings = {meaning(e) for _, e in items}
        split = len(meanings) > 1 and "" not in meanings
        for name, e in (items if split else items[:1]):
            gloss = gloss_name(name if split else base_name)
            if key(gloss) in taken or key(base_name) in taken_base:
                continue
            taken.add(key(gloss))
            english = meaning(e) or base_name.replace("-", " ").lower()
            category = (e.get("CDISemanticCategory") or e.get("LexicalClass") or "general").strip().lower() or "general"
            signs.append({"gloss": gloss, "english": english, "category": category,
                          "asl_citizen": name if split else base_name, "active": True, "avatar_ok": True, "curated": False})
    n_citizen = len(signs)

    # WLASL words ASL Citizen lacks: the avatar can sign them (clips_from_wlasl), recognition cannot
    if WLASL_INDEX.exists():
        for e in json.loads(WLASL_INDEX.read_text(encoding="utf-8")):
            gloss = gloss_name(e["gloss"])
            if not gloss or key(gloss) in taken:
                continue
            taken.add(key(gloss))
            signs.append({"gloss": gloss, "english": e["gloss"].lower(), "category": "general", "asl_citizen": "",
                          "active": True, "avatar_ok": True, "curated": False})
    EXTENDED.write_text("# Generated by training.build_vocab from ASL Citizen + ASL-LEX 2.0 + WLASL. Do not edit or commit.\n"
                        + yaml.safe_dump({"signs": signs}, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print(f"{len(base.active)} curated + {n_citizen} ASL Citizen + {len(signs) - n_citizen} WLASL-only signs "
          f"= {len(base.active) + len(signs)} -> {EXTENDED}")


if __name__ == "__main__":
    main()
